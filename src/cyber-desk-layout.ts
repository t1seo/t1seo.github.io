export function applyDeskLayout(root: ParentNode) {
  for (const [selector, [x, y, width, height]] of Object.entries(ELEMENTS)) {
    const element = root.querySelector<HTMLElement>(selector);
    if (!element) continue;
    Object.assign(element.style, {
      left: `${x / SOURCE_WIDTH * 100}%`,
      top: `${y / SOURCE_HEIGHT * 100}%`,
      width: `${width / SOURCE_WIDTH * 100}%`,
      height: `${height / SOURCE_HEIGHT * 100}%`,
    });
  }
  const monitor = root.querySelector<HTMLElement>('.night-monitor');
  if (monitor) monitor.style.clipPath = 'polygon(0 1.21%, 100% 0, 100% 100%, 0 96.99%)';
}
